export const REGISTER8: Design = (() => {
  let b = design(48, 48)
    .input("d", "s", 25, 8).output("q", "s", 16, 8).input("st", "s", 0).input(
      "clk",
      "s",
      2,
    );
  for (const [id, x, y, rotation] of PARTS) b = b.place(id, x, y, rotation);
  for (const [x, y, sides] of WIRES) b = b.wire(x, y, sides);
  for (const [x, y] of CROSSINGS) b = b.cross(x, y);
  return b.build();
})();
